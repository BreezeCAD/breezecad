"""Work planes and the ways of extruding: a block 40 x 40 x 10; a Ø20 cylinder drawn on a work plane 25 above the
base and extruded UP TO the block's top face; a lug extruded symmetrically from the XZ plane; a boss with a draft
on the cylinder's top. Reference by commands, then by hand two ways (work plane + «До грани»; sketches on faces)."""
import math

from _features import *

T10 = math.tan(math.radians(10))
B = 10 - 2 * 10 * T10                                    # the boss shrinks by the draft on every side
V_BLOCK = 40 * 40 * 10
V_CYL = math.pi * 100 * 15
V_LUG = 10 * 10 * 10                                     # x -30..-20 outside the block, y +-5, z 0..10
V_BOSS = 10 / 3 * (100 + 10 * B + B * B)
V_ALL = V_BLOCK + V_CYL + V_LUG + V_BOSS


def fit(b):
    b.key("f")   # «Показать всё»: the view after a sketch is the sketch's; then a little room round the part
    b.settle()
    zoom_out(b, 3)


def reference(b):
    new_part(b)
    s = b.run("sketch.create", plane="XY")["id"]
    b.run("sketch.add", sketch=s, items=[{"type": "rectangle", "center": [0, 0], "width": 40, "height": 40}])
    b.run("feature.extrude", sketch=s, distance=10)
    wp = b.run("work.plane", plane="XY", offset=25)
    check(wp["frame"]["origin"][2] == 25 and wp["frame"]["normal"] == [0.0, 0.0, 1.0], f"рабочая плоскость: {wp['frame']}")
    sk = b.run("sketch.create", plane=wp["name"])
    b.run("sketch.add", sketch=sk["id"], items=[{"type": "circle", "center": [0, 0], "diameter": 20}])
    top = [f for f in b.run("part.faces")["faces"] if f["kind"] == "plane" and f["normal"][2] > 0.99][0]
    r = b.run("part.create_feature", type="extrude", fields={"sketch": sk["id"], "extent": "toPlane", "toFace": top["ref"],
                                                           "operation": "join", "reversed": True})
    check(r.get("state") == "ok", f"до грани: {r}")
    b.settle()
    check(close(props(b)["volume_mm3"], V_BLOCK + V_CYL, 1e-9), f"цилиндр до грани: объём {props(b)['volume_mm3']}, ждали {V_BLOCK + V_CYL}")
    lug = b.run("sketch.create", plane="XZ")["id"]
    b.run("sketch.add", sketch=lug, items=[{"type": "rectangle", "corner": [-30, 0], "opposite": [-15, 10]}])
    b.run("feature.extrude", sketch=lug, distance=10, extent="symmetric")
    cap = face_at(b, (0, 0, 1), (0, 0, 25))
    sk = b.run("sketch.create", face=cap)
    b.run("sketch.add", sketch=sk["id"], items=[{"type": "rectangle", "center": uv_of(sk, (0, 0, 25)), "width": 10, "height": 10}])
    b.run("feature.extrude", sketch=sk["id"], distance=10, taper=10)
    b.settle()
    clean(b, "эталон")
    p = props(b)
    check(close(p["volume_mm3"], V_ALL, 1e-9), f"эталон: объём {p['volume_mm3']}, по формуле {V_ALL}")
    return p


def by_workplane(b):
    new_part(b)
    start_sketch_on_xy(b)
    zoom_out(b)
    rect_clicks(b, (-20, -20), (20, 20))
    finish_clicked(b)
    extrude_ribbon(b, 10)
    fit(b)
    b.click("feature.workPlane")
    b.settle()
    b.click_world(30, -30, 0)
    b.settle()
    b.fill("value", 25)
    b.click("done")
    b.settle()
    b.click("sketch.start")
    b.settle()
    b.click_world(18, 18, 25)           # the new plane
    b.settle()
    check(b.state().get("mode") == "sketch", "эскиз на рабочей плоскости не начался")
    zoom_out(b, 1)
    b.click("sketch.circle")
    b.fill("Диаметр", 20)
    b.click_sketch(0, 0)
    b.settle()
    b.key("Escape")
    finish_clicked(b)
    fit(b)
    b.click("feature.extrude")
    b.settle()
    b.click("depth|До плоскости", exact=False)
    b.click_world(15, -15, 10)          # the top face of the block
    b.settle()
    b.click("done")
    b.settle()
    clean(b, "рабочая плоскость")
    check(close(props(b)["volume_mm3"], V_BLOCK + V_CYL, 1e-6), f"цилиндр до грани рукой: объём {props(b)['volume_mm3']}")
    fit(b)
    b.click("sketch.start")
    b.settle()
    b.click_world(-30, 0, 30)           # the XZ plane, clear of the block in the view
    b.settle()
    check(b.state().get("mode") == "sketch", "эскиз на XZ не начался")
    zoom_out(b, 1)
    rect_clicks(b, (-30, 0), (-15, 10))
    finish_clicked(b)
    b.click("feature.extrude")
    b.settle()
    b.click("dir|В обе стороны поровну", exact=False)
    b.fill("Расстояние (всего)", 10)
    b.click("done")
    b.settle()
    clean(b, "симметричное")
    fit(b)
    b.click_world(6, 6, 25)             # the cylinder's top face
    b.click("sketch.start")
    b.settle()
    check(b.state().get("mode") == "sketch", "эскиз на торце цилиндра не начался")
    zoom_out(b, 1)
    rect_clicks(b, (-5, -5), (5, 5))
    finish_clicked(b)
    b.click("feature.extrude")
    b.settle()
    b.fill("Расстояние", 10)
    b.fill("Уклон", 10)
    b.click("done")
    b.settle()
    clean(b, "лента")
    return props(b)


